#!/usr/bin/env node
/*
 * Dev-only: converts Natural Earth 1:110m land outlines (TopoJSON from the
 * `world-atlas` npm package) into src/modules/worldLand.js — a compact,
 * dependency-free list of coastline polylines for the Situation Room globe.
 *
 * Usage:
 *   npm pack world-atlas@2 && tar xzf world-atlas-2.0.2.tgz
 *   node scripts/gen-land.mjs package/land-110m.json
 *
 * Data: Natural Earth (public domain) via world-atlas (ISC, © Michael Bostock).
 * Output coordinates are rounded to 0.1° and delta-encoded as integers.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) {
  console.error('Usage: node scripts/gen-land.mjs <path/to/land-110m.json>');
  process.exit(1);
}
const topo = JSON.parse(readFileSync(src, 'utf8'));
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;

// Decode quantized, delta-encoded TopoJSON arcs into lon/lat polylines.
const lines = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});

// Round to 0.1°, drop consecutive duplicates, delta-encode (integers ×10).
let points = 0;
const encoded = lines
  .map((ln) => {
    const q = [];
    for (const [lon, lat] of ln) {
      const p = [Math.round(lon * 10), Math.round(lat * 10)];
      const last = q[q.length - 1];
      if (!last || last[0] !== p[0] || last[1] !== p[1]) q.push(p);
    }
    return q;
  })
  .filter((q) => q.length > 1)
  .map((q) => {
    points += q.length;
    const out = [q[0][0], q[0][1]];
    for (let i = 1; i < q.length; i++) out.push(q[i][0] - q[i - 1][0], q[i][1] - q[i - 1][1]);
    return out.join(',');
  })
  .join(';');

const license = readFileSync(path.join(path.dirname(src), 'LICENSE'), 'utf8').trim().replace(/^/gm, ' * ');
const js = `/*
 * worldLand.js — GENERATED by scripts/gen-land.mjs. Do not edit by hand.
 * Coastline polylines (${points} points) for the Situation Room globe.
 * Source: Natural Earth 1:110m land (public domain), redistributed as TopoJSON
 * by the world-atlas package, whose licence notice follows:
 *
${license}
 */
(function (R) {
  'use strict';
  const RAW = '${encoded}';
  let cache = null;
  /** Returns an array of polylines, each a Float32Array of [lon, lat, lon, lat, …]. */
  R.worldLand = function () {
    if (cache) return cache;
    cache = RAW.split(';').map((s) => {
      const v = s.split(',').map(Number);
      const out = new Float32Array(v.length);
      let x = 0;
      let y = 0;
      for (let i = 0; i < v.length; i += 2) {
        x += v[i];
        y += v[i + 1];
        out[i] = x / 10;
        out[i + 1] = y / 10;
      }
      return out;
    });
    return cache;
  };
})(window.JAQAWorkspace);
`;
writeFileSync(path.join(root, 'src/modules/worldLand.js'), js);
console.log(`Wrote src/modules/worldLand.js — ${lines.length} arcs, ${points} points, ${js.length.toLocaleString()} bytes`);
