#!/usr/bin/env node
/*
 * build-arsenal.mjs — validate config/arsenal-catalog.mjs and emit
 * config/arsenal.json (embedded into the build for the Arsenal modules).
 *
 * Validation (fails the build on any violation, so the registry can't ship
 * malformed/un-linkable data):
 *   - every entry is exactly `owner/repo` (GitHub slug characters only);
 *   - no duplicate repo inside a single domain;
 *   - description present and reasonably short.
 * It records, per repo, every category it belongs to, and computes counts.
 * Run: node scripts/build-arsenal.mjs   (also invoked by scripts/build.mjs)
 * JAQA™ is a trademark of JAQA. © JAQA™. Licensed under AGPL-3.0-or-later.
 */
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DOMAINS } from '../config/arsenal-catalog.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SLUG = /^[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?\/[A-Za-z0-9._-]+$/;
const errors = [];

let totalEntries = 0;
const uniqueRepos = new Set();
const domains = DOMAINS.map((d) => {
  const seen = new Set();
  const categories = d.categories.map((c) => {
    const entries = c.entries.map(([repo, desc]) => {
      if (!SLUG.test(repo)) errors.push(`${d.id}/${c.id}: bad repo slug "${repo}"`);
      if (seen.has(repo.toLowerCase())) errors.push(`${d.id}: duplicate repo "${repo}" in domain`);
      seen.add(repo.toLowerCase());
      if (!desc || desc.length > 160) errors.push(`${d.id}/${c.id}: description for "${repo}" missing or too long`);
      totalEntries += 1;
      uniqueRepos.add(repo.toLowerCase());
      return { repo, url: 'https://github.com/' + repo, desc };
    });
    return { id: c.id, label: c.label, count: entries.length, entries };
  });
  return { id: d.id, label: d.label, blurb: d.blurb, count: seen.size, categories };
});

if (errors.length) {
  console.error('Arsenal catalogue invalid:\n  ' + errors.join('\n  '));
  process.exit(1);
}

const out = {
  generatedNote: 'GENERATED by scripts/build-arsenal.mjs from config/arsenal-catalog.mjs. Do not edit by hand.',
  totals: { domains: domains.length, categories: domains.reduce((n, d) => n + d.categories.length, 0), entries: totalEntries, uniqueRepos: uniqueRepos.size },
  domains
};
writeFileSync(path.join(root, 'config', 'arsenal.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`wrote config/arsenal.json — ${out.totals.domains} domains, ${out.totals.categories} categories, ${out.totals.entries} entries (${out.totals.uniqueRepos} unique repos).`);
